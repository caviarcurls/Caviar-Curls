  function getSelectedProduct(){
    const selectedLace = laceSelect.value;
    const selectedLength = lengthSelect.value;
    const bundleCount = isBundleProduct
      ? Number((selectedLace.match(/\d+/) || ["1"])[0])
      : 1;
    const singleBundlePrice = isBundleProduct && product.prices["1 Bundle"]
      ? Number(product.prices["1 Bundle"][selectedLength])
      : null;
    const finalPrice = singleBundlePrice
      ? singleBundlePrice * bundleCount
      : Number(product.prices[selectedLace][selectedLength]);

    return {
      key: productKey,
      title: product.title,
      name: `${product.title} / ${selectedLace} / ${selectedLength}\"`,
      type: selectedLace,
      length: `${selectedLength}\"`,
      price: finalPrice,
      image: productImage.src || product.image,
      quantity: 1
    };
  }

